/** URI de `part` com extensão dupla (`x.g.dart`, `x.freezed.dart`, `x.pb.dart`...). */
const GENERATED_PART_URI_RE = /^[^'"]*\.[A-Za-z0-9_]+\.dart$/;
/** Marcas de arquivo gerado no comentário de cabeçalho. */
const GENERATED_HEADER_RE =
  /\b(?:generated code|auto-?generated|do not (?:modify|edit)|@generated|generated by)\b/i;
const LANGUAGE_OVERRIDE_RE = /^\s*\/\/\s*@dart\s*=\s*(\d+\.\d+)\s*$/m;

/** Identificador DECLARADO no arquivo (classe, método, campo, variável, parâmetro...). */
export class DartIdentifier extends DartNodeBase {
  readonly kind: DartIdentifierKind;
  readonly name: string;
  /** Nome da classe/função onde foi declarado (`null` no nível superior). */
  readonly ownerName: string | null;

  /** @internal */
  constructor(file: DartFile, tok: number, kind: DartIdentifierKind, ownerName: string | null) {
    const t = file.lexed.tokens[tok];
    super(file, t.start, t.end);
    this.kind = kind;
    this.name = t.value;
    this.ownerName = ownerName;
  }
}

/** Trecho de nível superior que o parser não reconheceu. */
export class DartParseError extends DartNodeBase {
  readonly message: string;

  /** @internal */
  constructor(file: DartFile, start: number, end: number, message: string) {
    super(file, start, end);
    this.message = message;
  }
}

const fileCache = new Map<string, DartFile>();

/** Um arquivo Dart lido e analisado. Crie com `DartFile.read(caminho)`. */
export class DartFile {
  readonly path: DartPath;
  readonly exists: boolean;
  readonly source: string;
  /** `source.split("\n")` — o mesmo índice que os plugins usavam (`lines[i]` = linha `i + 1`). */
  readonly lines: readonly string[];
  readonly lineCount: number;

  private lexedCache: Lexed | null = null;
  private topCache: TopLevel | null = null;
  private declarationsCache: DartClass[] | null = null;
  private commentsCache: DartComment[] | null = null;
  private stringsCache: DartString[] | null = null;
  private stringByToken: Map<number, DartString> | null = null;
  private identifiersCache: DartIdentifier[] | null = null;
  private addedLinesSet: Set<number> | null = null;

  private constructor(filePath: string, source: string, exists: boolean) {
    this.path = DartPath.of(filePath);
    this.exists = exists;
    this.source = source;
    this.lines = source.split("\n");
    this.lineCount = this.lines.length;
  }

  // ─── Criação ────────────────────────────────────────────────────────────

  /**
   * Lê o arquivo do disco (`fs.readFileSync`, caminho relativo à raiz do
   * projeto, como o Danger informa) e devolve o modelo. Um parse por arquivo
   * por execução. Nunca lança exceção: arquivo inexistente vem com
   * `exists = false` e listas vazias.
   */
  static read(filePath: string): DartFile {
    const key = path.resolve(filePath);
    let file = fileCache.get(key);
    if (!file) {
      let source = "";
      let exists = false;
      try {
        source = fs.readFileSync(filePath, "utf-8");
        exists = true;
      } catch {
        // arquivo deletado ou inacessível
      }
      file = new DartFile(filePath, source, exists);
      fileCache.set(key, file);
    }
    return file;
  }

  /** Modelo a partir de um texto (testes, conteúdo que não está no disco). Sem cache. */
  static fromSource(source: string, filePath = "lib/memory.dart"): DartFile {
    return new DartFile(filePath, source, true);
  }

  /**
   * `read` + as linhas adicionadas no PR (`danger.git.structuredDiffForFile`),
   * para os plugins que só olham o diff. Sem diff, `addedLines` fica vazio.
   */
  static async readWithDiff(filePath: string): Promise<DartFile> {
    const file = DartFile.read(filePath);
    if (file.addedLinesSet === null) {
      const added = new Set<number>();
      try {
        const danger = (globalThis as any).danger;
        const diff = await danger?.git?.structuredDiffForFile(filePath);
        for (const chunk of diff?.chunks ?? []) {
          for (const change of chunk.changes ?? []) {
            if (change.type === "add" && typeof change.ln === "number") added.add(change.ln);
          }
        }
      } catch {
        // sem diff: nenhuma linha adicionada
      }
      file.addedLinesSet = added;
    }
    return file;
  }

  /**
   * Arquivos `.dart` modificados + criados no PR que existem no disco
   * (`ignore_files` já aplicado). Por padrão sem testes e sem gerados.
   * `createdFirst`: criados antes dos modificados (a ordem define a ordem das mensagens).
   */
  static changed(
    options: { includeTests?: boolean; includeGenerated?: boolean; createdFirst?: boolean } = {}
  ): DartFile[] {
    const danger = (globalThis as any).danger;
    const modified: string[] = danger?.git?.modified_files ?? [];
    const created: string[] = danger?.git?.created_files ?? [];
    const files = options.createdFirst ? [...created, ...modified] : [...modified, ...created];
    return files
      .filter((f) => {
        const p = DartPath.of(f);
        if (!p.isDart) return false;
        if (!options.includeTests && p.isTest) return false;
        if (!options.includeGenerated && p.isGenerated) return false;
        return fs.existsSync(f);
      })
      .map((f) => DartFile.read(f));
  }

  /** Limpa o cache de arquivos e caminhos (o `runPlugins` chama no início de cada execução). */
  static clearCache(): void {
    fileCache.clear();
    clearDartPathCaches();
  }

  // ─── Base (uso interno dos nós) ─────────────────────────────────────────

  /** @internal Tokens e comentários. */
  get lexed(): Lexed {
    if (this.lexedCache === null) this.lexedCache = lex(this.source);
    return this.lexedCache;
  }

  /** @internal Linha (base 1) de um offset. */
  lineAtOffset(offset: number): number {
    return lineOf(this.lexed, offset);
  }

  /** @internal Coluna (base 1) de um offset. */
  columnAtOffset(offset: number): number {
    return offset - this.lexed.lineStarts[this.lineAtOffset(offset) - 1] + 1;
  }

  private get top(): TopLevel {
    if (this.topCache === null) {
      try {
        this.topCache = scanTopLevel(this.lexed);
      } catch {
        this.topCache = {
          directives: [],
          types: [],
          typedefs: [],
          functions: [],
          variables: [],
          unknown: [],
        };
      }
    }
    return this.topCache;
  }

  // ─── Texto ──────────────────────────────────────────────────────────────

  /** Texto original da linha (base 1, sem `trim`). */
  lineAt(line: number): string {
    return this.lines[line - 1] ?? "";
  }

  /** Texto original das linhas `fromLine` a `toLine` (base 1, inclusive). */
  snippet(fromLine: number, toLine: number): string {
    return this.lines.slice(fromLine - 1, toLine).join("\n");
  }

  /**
   * A linha tem código: algum token começa ou passa por ela. Linha vazia, só
   * comentário ou só continuação de comentário de bloco → `false`. Linha
   * dentro de uma string multilinha conta como código.
   */
  isCode(line: number): boolean {
    return this.codeLines.has(line);
  }

  private codeLinesCache: Set<number> | null = null;
  private get codeLines(): Set<number> {
    if (this.codeLinesCache === null) {
      const set = new Set<number>();
      for (const t of this.lexed.tokens) {
        const a = this.lineAtOffset(t.start);
        const b = this.lineAtOffset(Math.max(t.start, t.end - 1));
        for (let l = a; l <= b; l++) set.add(l);
      }
      this.codeLinesCache = set;
    }
    return this.codeLinesCache;
  }

  /** A linha está dentro de um comentário (de linha, de doc ou de bloco) e não tem código. */
  isCommentLine(line: number): boolean {
    return !this.isCode(line) && this.comments.some((c) => line >= c.line && line <= c.endLine);
  }

  // ─── Linhas do PR ───────────────────────────────────────────────────────

  /** Linhas adicionadas no PR (base 1). Vazio se o arquivo não veio de `readWithDiff`. */
  get addedLines(): ReadonlySet<number> {
    return this.addedLinesSet ?? new Set();
  }

  isAdded(line: number): boolean {
    return this.addedLinesSet?.has(line) ?? false;
  }

  // ─── Fatos do arquivo ───────────────────────────────────────────────────

  /** `// @dart=3.x` do arquivo, ou `null`. */
  get languageVersionOverride(): string | null {
    return LANGUAGE_OVERRIDE_RE.exec(this.source)?.[1] ?? null;
  }

  /** Por que o arquivo é gerado: caminho, `part 'x.g.dart'` ou cabeçalho GENERATED; `null` se não for. */
  get generatedReason(): GeneratedReason | null {
    if (this.path.generatedReason) return this.path.generatedReason;
    if (this.parts.some((d) => GENERATED_PART_URI_RE.test(d.uri)))
      return GeneratedReason.GeneratedPart;
    const firstToken = this.lexed.tokens[0]?.start ?? this.source.length;
    for (const c of this.comments) {
      if (c.startOffset > firstToken) break;
      if (GENERATED_HEADER_RE.test(c.text)) return GeneratedReason.GeneratedHeader;
    }
    return null;
  }

  get isGenerated(): boolean {
    return this.generatedReason !== null;
  }

  /** URI ou nome da biblioteca de `part of`, ou `null`. */
  get partOf(): string | null {
    return this.directives.find((d) => d.kind === DartDirectiveKind.PartOf)?.uri ?? null;
  }

  /** `true` quando todo o nível superior foi reconhecido e todas as classes estão completas. */
  get isComplete(): boolean {
    return this.top.unknown.length === 0 && this.declarations.every((c) => c.isComplete);
  }

  /** Trechos de nível superior não reconhecidos. */
  get parseErrors(): readonly DartParseError[] {
    const { tokens } = this.lexed;
    return this.top.unknown.map(
      (u) =>
        new DartParseError(
          this,
          tokens[u.startTok].start,
          tokens[u.endTok].end,
          "trecho não reconhecido"
        )
    );
  }

  // ─── Diretivas ──────────────────────────────────────────────────────────

  private directivesCache: DartDirective[] | null = null;
  get directives(): readonly DartDirective[] {
    if (this.directivesCache === null)
      this.directivesCache = this.top.directives.map((d) => new DartDirective(this, d));
    return this.directivesCache;
  }

  get imports(): readonly DartDirective[] {
    return this.directives.filter((d) => d.kind === DartDirectiveKind.Import);
  }

  get exports(): readonly DartDirective[] {
    return this.directives.filter((d) => d.kind === DartDirectiveKind.Export);
  }

  get parts(): readonly DartDirective[] {
    return this.directives.filter((d) => d.kind === DartDirectiveKind.Part);
  }

  // ─── Declarações ────────────────────────────────────────────────────────

  /** Todas as declarações de tipo (class, enum, mixin, extension...), na ordem do arquivo. */
  get declarations(): readonly DartClass[] {
    if (this.declarationsCache === null)
      this.declarationsCache = this.top.types.map((t) => new DartClass(this, t));
    return this.declarationsCache;
  }

  /** Só `class` (inclui `abstract`, `sealed`, `base`, `interface`, `final`, `mixin class` e mixin application). */
  get classes(): readonly DartClass[] {
    return this.declarations.filter(
      (c) => c.kind === DartDeclarationKind.Class || c.kind === DartDeclarationKind.MixinApplication
    );
  }

  get enums(): readonly DartClass[] {
    return this.declarations.filter((c) => c.kind === DartDeclarationKind.Enum);
  }

  get mixins(): readonly DartClass[] {
    return this.declarations.filter((c) => c.kind === DartDeclarationKind.Mixin);
  }

  get extensions(): readonly DartClass[] {
    return this.declarations.filter((c) => c.kind === DartDeclarationKind.Extension);
  }

  get extensionTypes(): readonly DartClass[] {
    return this.declarations.filter((c) => c.kind === DartDeclarationKind.ExtensionType);
  }

  private typedefsCache: DartTypedef[] | null = null;
  get typedefs(): readonly DartTypedef[] {
    if (this.typedefsCache === null)
      this.typedefsCache = this.top.typedefs.map((t) => new DartTypedef(this, t));
    return this.typedefsCache;
  }

  private functionsCache: DartFunction[] | null = null;
  /** Funções, getters e setters de nível superior. */
  get functions(): readonly DartFunction[] {
    if (this.functionsCache === null)
      this.functionsCache = this.top.functions.map((f) => new DartFunction(this, f, new Set()));
    return this.functionsCache;
  }

  private variablesCache: DartTopLevelVariable[] | null = null;
  /** Variáveis de nível superior (uma por nome em `final a = 1, b = 2;`). */
  get variables(): readonly DartTopLevelVariable[] {
    if (this.variablesCache === null) {
      this.variablesCache = this.top.variables.flatMap((m) =>
        m.vars.map(
          (v) => new DartTopLevelVariable(this, m, v.nameTok, v.initStartTok, v.initEndTok)
        )
      );
    }
    return this.variablesCache;
  }

  /** Declaração de tipo que contém a linha (a mais interna não existe: Dart não aninha classes). */
  declarationAt(line: number): DartClass | null {
    return this.declarations.find((c) => c.containsLine(line)) ?? null;
  }

  /** Declaração de tipo pelo nome. */
  findClass(name: string): DartClass | null {
    return this.declarations.find((c) => c.name === name) ?? null;
  }

  // ─── Comentários e strings ──────────────────────────────────────────────

  /** Todos os comentários, na ordem do arquivo. */
  get comments(): readonly DartComment[] {
    if (this.commentsCache === null) {
      const { tokens } = this.lexed;
      let t = 0;
      this.commentsCache = this.lexed.comments.map((c) => {
        while (t < tokens.length && tokens[t].end <= c.start) t++;
        const prev = tokens[t - 1];
        const isTrailing =
          prev !== undefined && this.lineAtOffset(prev.end - 1) === this.lineAtOffset(c.start);
        return new DartComment(this, c, isTrailing);
      });
    }
    return this.commentsCache;
  }

  /** Todas as strings literais, na ordem do arquivo, com o papel sintático (`role`). */
  get strings(): readonly DartString[] {
    if (this.stringsCache === null) this.buildStrings();
    return this.stringsCache ?? [];
  }

  /** @internal String do token `k` (ou `null`). */
  stringAtToken(k: number): DartString | null {
    if (this.stringByToken === null) this.buildStrings();
    return this.stringByToken?.get(k) ?? null;
  }

  private buildStrings(): void {
    const { tokens } = this.lexed;
    const directiveRanges = this.top.directives.map((d) => [d.startTok, d.endTok] as const);
    const out: DartString[] = [];
    const byToken = new Map<number, DartString>();
    // pilha de brackets: índice do token de abertura
    const stack: number[] = [];
    const annotationParens = new Set<number>();
    for (let k = 0; k < tokens.length; k++) {
      const t = tokens[k];
      if (t.kind === "punct") {
        if (t.value === "(" || t.value === "[" || t.value === "{") {
          if (t.value === "(" && isAnnotationParen(tokens, k)) annotationParens.add(k);
          stack.push(k);
        } else if (t.value === ")" || t.value === "]" || t.value === "}") {
          stack.pop();
        }
        continue;
      }
      if (t.kind !== "string") continue;
      let role = DartStringRole.Value;
      let callee: string | null = null;
      let label: string | null = null;
      const top = stack.length > 0 ? stack[stack.length - 1] : -1;
      // `'a' 'b'`: o pedaço seguinte herda o contexto do primeiro
      let first = k;
      while (first > 0 && tokens[first - 1].kind === "string") first--;
      const before = tokens[first - 1];
      let last = k;
      while (last + 1 < tokens.length && tokens[last + 1].kind === "string") last++;
      const after = tokens[last + 1];
      if (directiveRanges.some(([a, b]) => k >= a && k <= b)) {
        role = DartStringRole.DirectiveUri;
      } else if (stack.some((o) => annotationParens.has(o))) {
        role = DartStringRole.AnnotationArgument;
      } else if (isIdent(before, "case")) {
        role = DartStringRole.CaseLabel;
      } else if (
        top >= 0 &&
        isPunct(tokens[top], "{") &&
        isPunct(after, ":") &&
        (isPunct(before, "{") || isPunct(before, ","))
      ) {
        role = DartStringRole.MapKey;
      } else if (
        top >= 0 &&
        isPunct(tokens[top], "[") &&
        isPunct(before, "[") &&
        isPunct(after, "]") &&
        isIndexBracket(tokens, top)
      ) {
        role = DartStringRole.IndexKey;
      } else if (top >= 0 && isPunct(tokens[top], "(") && isCallParen(tokens, top)) {
        role = DartStringRole.CallArgument;
        callee = calleeBefore(this, top);
        // rótulo: `nome: 'x'` no pedaço do argumento
        let j = first - 1;
        let depth = 0;
        while (j > top) {
          const tj = tokens[j];
          if (isPunct(tj, ")") || isPunct(tj, "]") || isPunct(tj, "}")) depth++;
          else if (isPunct(tj, "(") || isPunct(tj, "[") || isPunct(tj, "{")) depth--;
          else if (depth === 0 && isPunct(tj, ",")) break;
          j--;
        }
        if (isIdent(tokens[j + 1]) && isPunct(tokens[j + 2], ":")) label = tokens[j + 1].value;
      }
      const s = new DartString(this, k, role, callee, label);
      out.push(s);
      byToken.set(k, s);
    }
    this.stringsCache = out;
    this.stringByToken = byToken;
  }

  // ─── Chamadas e identificadores ─────────────────────────────────────────

  private callsCache: DartCall[] | null = null;
  /**
   * Todas as chamadas do arquivo: corpos de métodos/funções/construtores,
   * inicializadores de campos e variáveis, initializer lists, valores padrão e
   * argumentos de valores de enum. Não inclui anotações.
   */
  calls(): readonly DartCall[] {
    if (this.callsCache === null) {
      const ranges: [number, number][] = [];
      for (const cls of this.declarations) {
        for (const m of cls.members) ranges.push(...m.expressionRanges());
        for (const v of cls.enumValues) ranges.push(...v.expressionRanges());
        if (cls.primaryConstructor) ranges.push(...cls.primaryConstructor.expressionRanges());
      }
      for (const f of this.functions) ranges.push(...f.expressionRanges());
      for (const v of this.variables) ranges.push(...v.expressionRanges());
      const calls: DartCall[] = [];
      for (const [a, b] of ranges) {
        if (a < 0 || b < a) continue;
        const closures = scanClosures(this, a, b);
        calls.push(...scanCalls(this, a, b, closures));
      }
      this.callsCache = calls.sort((x, y) => x.startOffset - y.startOffset);
    }
    return this.callsCache;
  }

  /** Identificadores DECLARADOS no arquivo (não os usos), na ordem do arquivo. */
  get identifiers(): readonly DartIdentifier[] {
    if (this.identifiersCache === null) this.identifiersCache = buildIdentifiers(this);
    return this.identifiersCache;
  }
}

function isAnnotationParen(tokens: Lexed["tokens"], open: number): boolean {
  let j = open - 1;
  while (j >= 1 && tokens[j].kind === "ident") {
    if (isPunct(tokens[j - 1], "@")) return true;
    if (isPunct(tokens[j - 1], ".")) {
      j -= 2;
      continue;
    }
    return false;
  }
  return false;
}

/** Palavras depois das quais `[` abre uma lista, e não um índice. */
const LIST_PREFIX_WORDS = new Set([
  "const",
  "return",
  "yield",
  "await",
  "in",
  "case",
  "else",
  "is",
  "as",
  "throw",
  "new",
  "when",
]);

function isIndexBracket(tokens: Lexed["tokens"], open: number): boolean {
  const prev = tokens[open - 1];
  if (prev === undefined) return false;
  if (prev.kind === "ident") return !LIST_PREFIX_WORDS.has(prev.value);
  return isPunct(prev, ")") || isPunct(prev, "]") || isPunct(prev, "!");
}

const NOT_CALL_WORDS = new Set([
  "if",
  "for",
  "while",
  "switch",
  "catch",
  "return",
  "await",
  "assert",
  "Function",
  "super",
  "this",
]);

function isCallParen(tokens: Lexed["tokens"], open: number): boolean {
  const prev = tokens[open - 1];
  if (!prev) return false;
  if (prev.kind === "ident")
    return !NOT_CALL_WORDS.has(prev.value) || prev.value === "super" || prev.value === "this";
  return isPunct(prev, ">");
}

/** Callee (receptor + nome) da chamada cujo `(` está em `open`. */
function calleeBefore(file: DartFile, open: number): string | null {
  const { tokens } = file.lexed;
  let nameTok = open - 1;
  if (isPunct(tokens[nameTok], ">")) {
    let depth = 0;
    for (let k = nameTok; k >= 0; k--) {
      if (isPunct(tokens[k], ">")) depth++;
      else if (isPunct(tokens[k], "<") && --depth === 0) {
        nameTok = k - 1;
        break;
      }
    }
  }
  if (!isIdent(tokens[nameTok])) return null;
  let start = nameTok;
  while (
    start >= 2 &&
    (isPunct(tokens[start - 1], ".") || isPunct(tokens[start - 1], "?.")) &&
    isIdent(tokens[start - 2])
  ) {
    start -= 2;
  }
  return compactText(file, start, nameTok);
}

function buildIdentifiers(file: DartFile): DartIdentifier[] {
  const { tokens } = file.lexed;
  const out: DartIdentifier[] = [];
  const add = (tok: number, kind: DartIdentifierKind, owner: string | null): void => {
    if (tok >= 0 && tokens[tok]?.kind === "ident")
      out.push(new DartIdentifier(file, tok, kind, owner));
  };
  const declKind: Record<string, DartIdentifierKind> = {
    class: DartIdentifierKind.Class,
    mixinApplication: DartIdentifierKind.Class,
    enum: DartIdentifierKind.Enum,
    mixin: DartIdentifierKind.Mixin,
    extension: DartIdentifierKind.Extension,
    extensionType: DartIdentifierKind.ExtensionType,
  };
  const addParams = (params: readonly DartParameter[], owner: string | null): void => {
    for (const p of params) add(p.nameTokIndex, DartIdentifierKind.Parameter, owner);
  };
  const addBody = (body: DartBody | null, owner: string | null): void => {
    if (!body) return;
    for (const v of body.localVariables)
      add(v.nameTokIndex, DartIdentifierKind.LocalVariable, owner);
    for (const c of body.closures) {
      if (c.name) add(c.openTok, DartIdentifierKind.LocalFunction, owner);
      addParams(c.parameters, owner);
    }
    for (const t of body.tryStatements) {
      for (const c of t.catches) {
        for (const tok of c.variableTokens) add(tok, DartIdentifierKind.CatchVariable, owner);
      }
    }
  };
  for (const cls of file.declarations) {
    if (cls.raw.nameTok >= 0) add(cls.raw.nameTok, declKind[cls.raw.kind], null);
    for (const tp of cls.typeParameters)
      add(tp.nameTokIndex, DartIdentifierKind.TypeParameter, cls.name);
    for (const v of cls.enumValues) add(v.headTokIndex, DartIdentifierKind.EnumValue, cls.name);
    for (const f of cls.fields) add(f.nameTokIndex, DartIdentifierKind.Field, cls.name);
    for (const c of cls.constructors) {
      if (c.constructorName && !c.isPrimary)
        add(c.nameTokIndex, DartIdentifierKind.Constructor, cls.name);
      addParams(
        c.parameters.filter((p) => p.source !== DartParameterSource.Declaring),
        cls.name
      );
      addBody(c.body, cls.name);
    }
    for (const m of cls.methods) {
      if (m.memberKind === DartMemberKind.Operator) continue;
      const kind =
        m.memberKind === DartMemberKind.Getter
          ? DartIdentifierKind.Getter
          : m.memberKind === DartMemberKind.Setter
            ? DartIdentifierKind.Setter
            : DartIdentifierKind.Method;
      add(m.rawMember.nameTok, kind, cls.name);
      for (const tp of m.typeParameters)
        add(tp.nameTokIndex, DartIdentifierKind.TypeParameter, m.name);
      addParams(m.parameters, cls.name);
      addBody(m.body, cls.name);
    }
  }
  for (const t of file.typedefs) {
    add(t.nameTokIndex, DartIdentifierKind.Typedef, null);
    for (const tp of t.typeParameters)
      add(tp.nameTokIndex, DartIdentifierKind.TypeParameter, t.name);
  }
  for (const f of file.functions) {
    add(f.rawMember.nameTok, DartIdentifierKind.Function, null);
    for (const tp of f.typeParameters)
      add(tp.nameTokIndex, DartIdentifierKind.TypeParameter, f.name);
    addParams(f.parameters, f.name);
    addBody(f.body, f.name);
  }
  for (const v of file.variables) add(v.nameTokIndex, DartIdentifierKind.TopLevelVariable, null);
  const seen = new Set<number>();
  return out
    .filter((i) => (seen.has(i.startOffset) ? false : (seen.add(i.startOffset), true)))
    .sort((a, b) => a.startOffset - b.startOffset);
}
